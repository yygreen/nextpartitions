"""Write SUMMARY.md from the area files and prospects.csv (run after build.py)."""
import csv, collections, glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
AREAS = json.load(open(os.path.join(HERE, 'areas.json')))  # slug, name, state
rows = list(csv.DictReader(open(os.path.join(HERE, 'prospects.csv'))))

def key(n):
    n = re.sub(r'[^a-z0-9 ]', '', n.lower())
    return ' '.join(re.sub(r'\b(inc|llc|co|corp|company|ltd|the)\b', '', n).split())

uniq = {}
for r in rows:
    uniq.setdefault(key(r['name']), r)
strong = [r for r in uniq.values() if r['verdict'] == 'strong']
install_only = sorted((r for r in rows if r['verdict'] == 'strong' and r['sells_partitions'] != 'yes'),
                      key=lambda r: (r['area'], -int(r['score'])))
lic = collections.Counter(r['license_status'] or 'not checked' for r in uniq.values())

per = {}
for a in AREAS:
    f = os.path.join(HERE, a['slug'] + '.json')
    c = json.load(open(f))['candidates'] if os.path.exists(f) else []
    per[a['slug']] = dict(name=a['name'], state=a['state'],
                          strong=sum(x['verdict'] == 'strong' for x in c),
                          possible=sum(x['verdict'] == 'possible' for x in c),
                          install_only=sum(x['verdict'] == 'strong' and x['sells_partitions'] != 'yes' for x in c))

L = []
w = L.append
w('# Installer prospects: summary\n')
w('Generated by `summary.py` from the area files. Research only: nobody has been contacted. Strong = partition installation shown for commercial clients; possible = likely but unproven. "Install-only" = strong and doesn\'t sell partitions itself (lowest buy-around risk).\n')
w('## Totals\n')
w(f'- {len(rows)} prospect rows (strong and possible) for 99 areas; {len(uniq)} unique businesses, since some serve several areas.')
w(f'- {len(strong)} unique strong candidates, {len({key(r["name"]) for r in install_only})} of them install-only.')
w(f'- Areas with 3+ strong: {sum(p["strong"] >= 3 for p in per.values())}; with 1 or 2: {sum(0 < p["strong"] < 3 for p in per.values())}; with none: {sum(p["strong"] == 0 for p in per.values())}.')
w('- Registration checks (unique businesses): ' + ', '.join(f'{k.replace("_", " ")} {v}' for k, v in lic.most_common()) + '.\n')
w('## By area\n')
w('| Area | State | Strong | Install-only | Possible |\n|---|---|---|---|---|')
for s, p in sorted(per.items(), key=lambda kv: (-kv[1]['strong'], -kv[1]['possible'], kv[0])):
    w(f'| {p["name"]} | {p["state"]} | {p["strong"]} | {p["install_only"]} | {p["possible"]} |')
w('\n## Install-only strong candidates (start outreach here)\n')
w('| Area | Business | Base city | Phone | Website | Score |\n|---|---|---|---|---|---|')
for r in install_only:
    w(f'| {per[r["area"]]["name"]} | {r["name"]} | {r["base_city"]} | {r["phone"]} | {r["website"]} | {r["score"]} |')
w('\n## Registrations to check by hand\n')
w('Strong and possible businesses whose registry couldn\'t be searched automatically (`not_online`) or where no record was found (`not_found`), by state.\n')
by_state = collections.defaultdict(list)
for r in uniq.values():
    if r['license_status'] in ('not_online', 'not_found', ''):
        by_state[r['state']].append(r)
w('| State | Businesses | Not online | Not found | Not checked |\n|---|---|---|---|---|')
for st, rs in sorted(by_state.items(), key=lambda kv: -len(kv[1])):
    c = collections.Counter(r['license_status'] or 'none' for r in rs)
    w(f'| {st} | {len(rs)} | {c["not_online"]} | {c["not_found"]} | {c["none"]} |')
w('\n## Areas with no strong candidate\n')
w(', '.join(p['name'] for s, p in sorted(per.items()) if p['strong'] == 0) + '.\n')
w('These need phone calls, the Blue Book (blocks automated access) or a general Division 10 or commercial carpentry subcontractor recruited for partition work.')
open(os.path.join(HERE, 'SUMMARY.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L[:8]))
