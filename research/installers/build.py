"""Merge agent results (raw/*.json) into per-area files, prospects.csv and gaps.md.

Each raw file is one workflow result: {"areas": [...], "licenses": [...]}.
Score (100): partition work shown 40 (likely 20), commercial 20 (mostly 15), registration
confirmed 15, reviews 4.5+ from 10+ 10, in or near the area 10 (nearby 5), doesn't sell
partitions itself 5. Rejected candidates are kept in the area file but left out of the CSV.
"""
import csv, glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))

def key(name):
    n = re.sub(r'[^a-z0-9 ]', '', name.lower())
    n = re.sub(r'\b(inc|llc|co|corp|company|ltd|the)\b', '', n)
    return ' '.join(n.split())

def score(c, lic):
    s = {'yes': 40, 'likely': 20}.get(c.get('installs_partitions'), 0)
    s += {'yes': 20, 'mostly': 15}.get(c.get('commercial'), 0)
    s += 15 if lic and lic.get('status') == 'found_active' else 0
    if (c.get('rating') or 0) >= 4.5 and (c.get('review_count') or 0) >= 10: s += 10
    s += {'yes': 10, 'nearby': 5}.get(c.get('within_area'), 0)
    s += 5 if c.get('sells_partitions') == 'no' else 0
    return s

areas, lic = {}, {}
for f in sorted(glob.glob(os.path.join(HERE, 'raw', '*.json'))):
    d = json.load(open(f))
    for a in d.get('areas', []): areas[a['area']] = a
    for st in d.get('licenses', []):
        for r in st.get('results', []): lic[(r['area'], key(r['name']))] = r

rows, gaps = [], []
seen = {}
for slug, a in sorted(areas.items()):
    out = []
    best = {}
    for c in a['checked']:
        k = key(c['name'])
        if k in best and best[k]['verdict'] != 'reject': continue
        best[k] = c
    for k, c in best.items():
        l = lic.get((slug, k))
        c = dict(c, license=l, score=score(c, l))
        out.append(c)
        if c['verdict'] != 'reject':
            seen.setdefault(k, []).append(slug)
            rows.append(c | {'area': slug})
    out.sort(key=lambda c: (c['verdict'] == 'reject', -c['score']))
    json.dump({'area': slug, 'found_count': a.get('found_count'), 'sources_tried': a.get('sources_tried'), 'candidates': out},
              open(os.path.join(HERE, f'{slug}.json'), 'w'), indent=1)
    strong = sum(1 for c in out if c['verdict'] == 'strong')
    possible = sum(1 for c in out if c['verdict'] == 'possible')
    if strong < 3: gaps.append((slug, strong, possible))

rows.sort(key=lambda r: (r['area'], -r['score']))
cols = ['area', 'score', 'verdict', 'name', 'base_city', 'state', 'website', 'phone', 'email', 'contact_page',
        'installs_partitions', 'commercial', 'sells_partitions', 'within_area', 'rating', 'review_count',
        'license_status', 'license_number', 'also_in_areas', 'red_flags', 'partition_evidence', 'evidence_urls', 'reason']
with open(os.path.join(HERE, 'prospects.csv'), 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=cols)
    w.writeheader()
    for r in rows:
        l = r.get('license') or {}
        w.writerow({**{c: r.get(c, '') for c in cols},
                    'license_status': l.get('status', ''), 'license_number': l.get('license_number', ''),
                    'also_in_areas': ' '.join(s for s in seen[key(r['name'])] if s != r['area']),
                    'red_flags': '; '.join(r.get('red_flags') or []),
                    'evidence_urls': ' '.join(r.get('evidence_urls') or [])})

with open(os.path.join(HERE, 'gaps.md'), 'w') as f:
    f.write('# Areas with fewer than 3 strong candidates\n\nGenerated by build.py.\n\n| Area | Strong | Possible |\n|---|---|---|\n')
    for g in gaps: f.write(f'| {g[0]} | {g[1]} | {g[2]} |\n')
print(len(areas), 'areas,', len(rows), 'prospects,', len(gaps), 'gaps')
