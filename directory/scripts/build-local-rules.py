"""Generates supabase/migrations/20261103000400_laws_and_local_rules_data.sql:
  - each state hub's governing law, from research/state-licensing/states.json (law, law_url)
  - each area page's local rule, from research/local-rules/cities.json (note, authority, source_url)

Usage: python3 scripts/build-local-rules.py
Don't edit the generated SQL by hand. Research notes, not legal advice: the lawyer reviews before launch.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESEARCH = os.path.join(ROOT, '..', 'research')
OUT = os.path.join(ROOT, 'supabase', 'migrations', '20261103000600_laws_and_local_rules_data.sql')
CHECKED = '2026-11-03'

def q(v):
    return 'null' if v in (None, '') else "'" + str(v).replace("'", "''") + "'"
def url(v):
    return v if isinstance(v, str) and v.startswith('http') else None

states = json.load(open(os.path.join(RESEARCH, 'state-licensing', 'states.json')))
cities = json.load(open(os.path.join(RESEARCH, 'local-rules', 'cities.json')))
lines = []
for s in sorted(states, key=lambda s: s['code']):
    if s.get('law'):
        lines.append(f"update dir_states set license_law = {q(s['law'])}, license_law_url = {q(url(s.get('law_url')))} where code = {q(s['code'])};")
for c in sorted(cities, key=lambda c: c['slug']):
    if c.get('note'):
        lines.append(f"update dir_areas set local_note = {q(c['note'])}, local_authority = {q(c.get('authority'))}, "
                     f"local_source_url = {q(url(c.get('source_url')))}, local_code = {q(c.get('code_citation'))}, local_checked = '{CHECKED}' where slug = {q(c['slug'])};")
with open(OUT, 'w') as f:
    f.write('-- State laws and local installer rules (research 2026-11-03, research/state-licensing/ and research/local-rules/).\n'
            '-- Generated by scripts/build-local-rules.py; don\'t edit by hand.\n\n' + '\n'.join(lines) + '\n')
print(len(states), 'states,', len(cities), 'cities ->', OUT)
