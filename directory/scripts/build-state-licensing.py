"""Generates supabase/migrations/20261103000200_state_licensing.sql from research/state-licensing/states.json:
the public licensing summary on each state hub, plus the internal confidence and notes (dir_state_notes, admins only).

Usage: python3 scripts/build-state-licensing.py
Edit states.json (or rerun the research), then rerun this. Don't edit the generated SQL by hand.
These are research notes, not legal advice: the lawyer reviews the wording before launch (CLAUDE.md).
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '..', 'research', 'state-licensing', 'states.json')
OUT = os.path.join(ROOT, 'supabase', 'migrations', '20261103000200_state_licensing.sql')
CHECKED = '2026-11-03'
STATUSES = {'license_required', 'above_threshold', 'registration_only', 'no_state_license', 'unclear'}

data = json.load(open(SRC))
codes = re.findall(r"\('[a-z-]+', '([A-Z]{2})',", open(os.path.join(ROOT, 'supabase', 'migrations', '20261103000000_states.sql')).read())
missing = sorted(set(codes) - {d['code'] for d in data})
if missing:
    raise SystemExit(f'states.json is missing {missing}')

def q(v):
    return 'null' if v in (None, '') else "'" + str(v).replace("'", "''") + "'"

lines = []
for d in sorted(data, key=lambda d: d['code']):
    status = d['status'] if d['status'] in STATUSES else 'unclear'
    cents = int(d['threshold_usd'] * 100) if d.get('threshold_usd') else None
    src = d.get('source_url') if str(d.get('source_url', '')).startswith('http') else None
    lines.append(f"update dir_states set license_status = {q(status)}, license_threshold_cents = {cents if cents else 'null'}, "
                 f"license_summary = {q(d['summary'])}, license_authority = {q(d.get('authority'))}, license_source_url = {q(src)}, "
                 f"license_checked = '{CHECKED}' where code = {q(d['code'])};")
    lines.append(f"insert into dir_state_notes (slug, confidence, note) select slug, {q(d.get('confidence'))}, {q(' '.join(x for x in [d.get('note'), d.get('law_flag') and 'Law: ' + d['law_flag']] if x))} "
                 f"from dir_states where code = {q(d['code'])} on conflict (slug) do update set confidence = excluded.confidence, note = excluded.note;")

with open(OUT, 'w') as f:
    f.write('-- Who may install partitions, by state (research 2026-11-03, research/state-licensing/states.json).\n'
            '-- Generated by scripts/build-state-licensing.py; don\'t edit by hand. Research notes, not legal advice:\n'
            '-- confirm each rule with its authority, and the lawyer reviews the wording before launch.\n\n'
            + '\n'.join(lines) + '\n')
print(len(data), 'states ->', OUT)
