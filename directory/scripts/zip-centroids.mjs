// Generates supabase/migrations/20261021000100_zip_centroids_data.sql: one point per US ZIP code.
// Source: US Census Bureau 2024 Gazetteer, ZIP Code Tabulation Areas (public domain):
//   https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip
// Run: node scripts/zip-centroids.mjs path/to/2024_Gaz_zcta_national.txt
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const src = process.argv[2]
if (!src) throw new Error('usage: node scripts/zip-centroids.mjs 2024_Gaz_zcta_national.txt')

const [header, ...lines] = readFileSync(src, 'utf8').split(/\r?\n/).filter((l) => l.trim())
const cols = header.split('\t').map((c) => c.trim())
const [zipCol, latCol, lngCol] = ['GEOID', 'INTPTLAT', 'INTPTLONG'].map((c) => cols.indexOf(c))
if ([zipCol, latCol, lngCol].includes(-1)) throw new Error(`unexpected columns: ${cols.join(', ')}`)

const rows = lines.map((l) => {
  const f = l.split('\t').map((c) => c.trim())
  const zip = f[zipCol], lat = Number(f[latCol]), lng = Number(f[lngCol])
  if (!/^\d{5}$/.test(zip) || !Number.isFinite(lat) || !Number.isFinite(lng)) throw new Error(`bad row: ${l}`)
  return `('${zip}',${lat.toFixed(4)},${lng.toFixed(4)})`
})

const chunks = []
for (let n = 0; n < rows.length; n += 1000) {
  chunks.push(`insert into dir_zip_centroids (zip, lat, lng) values\n${rows.slice(n, n + 1000).join(',\n')}\n` +
    'on conflict (zip) do update set lat = excluded.lat, lng = excluded.lng;')
}

const out = join(dirname(fileURLToPath(import.meta.url)), '../supabase/migrations/20261021000100_zip_centroids_data.sql')
writeFileSync(out, `-- ${rows.length} US ZIP code centres. Generated by scripts/zip-centroids.mjs; don't edit by hand.
-- Source: US Census Bureau 2024 Gazetteer, ZIP Code Tabulation Areas (internal points), public domain.
-- https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip

${chunks.join('\n\n')}

-- Jobs and installers added before the ZIP data was loaded.
update dir_jobs j set lat = z.lat, lng = z.lng from dir_zip_centroids z where z.zip = j.zip and j.lat is null;
update dir_installers i set lat = z.lat, lng = z.lng from dir_zip_centroids z where z.zip = i.base_zip and i.lat is null;
`)
console.log(`wrote ${rows.length} ZIP codes to ${out}`)
